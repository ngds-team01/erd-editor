// 0 이상 length 미만의 정수
// random: 0 이상 1 미만 값을 돌려주는 함수, 테스트에서 결과를 고정하려고 인자로 받음
function randomIndex(length: number, random: () => number): number {
  return Math.floor(random() * length)
}

// 형용사 1개와 동물 1개를 무작위로 골라 띄어 씀 (원본 getRandomNickname과 같은 구조)
export function randomNickname(random: () => number = Math.random): string {
  const adjective = ADJECTIVES[randomIndex(ADJECTIVES.length, random)]
  const animal = ANIMALS[randomIndex(ANIMALS.length, random)]
  return `${adjective} ${animal}`
}
